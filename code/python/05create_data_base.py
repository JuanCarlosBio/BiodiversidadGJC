import geopandas as gpd
import pandas as pd
from shapely.geometry import Point

## Load the data
df_species = pd.read_csv("data/species/processed/coord_species.tsv", 
                         delimiter="\t")

gc_pne = (
    gpd.read_file("data/gran_canaria_shp/gc_pne.shp")
      .to_crs(4326)
  )

gc_zec = (
    gpd.read_file("data/gran_canaria_shp/gc_zec.shp")
      .to_crs(epsg = 4326)
  )

gc_muni = (
    gpd.read_file("data/gran_canaria_shp/gc_muni.shp")
      .to_crs(epsg = 4326)
)

# Create a geometry column from the latitude and longitude
geometry = [
    Point(xy) for xy in zip(df_species['longitude'], df_species['latitude'])
  ]

# Create a GeoDataFrame
species_points = gpd.GeoDataFrame(df_species, geometry=geometry)

# Set the coordinate reference system (CRS) to WGS84 (EPSG:4326)
species_points.set_crs(epsg=4326, inplace=True)

species_pne = gpd.sjoin(
    species_points,
    gc_pne,
    how="left",
    predicate="within"
)

# Remove the index column generated by the spatial join
species_pne = species_pne.drop(columns=["index_right"])

species_pne_zec = gpd.sjoin(
    species_pne,
    gc_zec,
    how="left",
    predicate="within",
    lsuffix="left",
    rsuffix="right"
)

species_pne_zec = species_pne_zec.drop(columns=["index_right"])

gc_muni = gc_muni.rename(
    columns={col: f"{col}_muni" for col in gc_muni.columns if col != "geometry"}
)

species_pne_zec_muni = gpd.sjoin(
    species_pne_zec,
    gc_muni,
    how="left",
    predicate="within",
    lsuffix="left",
    rsuffix="right"
)

species_pne_zec_muni = species_pne_zec_muni.drop(columns=["index_right"])

species_pne_zec_muni = species_pne_zec_muni[species_pne_zec_muni.geometry.distance(Point(-15.6, 27.96)) < 5]

species_pne_zec_muni.to_csv("data/species/processed/species_data_base.csv", index=False)
species_pne_zec_muni.to_file("data/species/gran_canaria_shp/processed/species_data_base.shp", index=False)